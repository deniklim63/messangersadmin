function normalize(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/^(г\.|город|гор\.)\s*/i, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s+/g, " ")
    .trim();
}

const KNOWN = new Map(KNOWN_CITIES.map((city) => [normalize(city), city]));

/** Поиск по своему списку: точное совпадение после нормализации. */
export function findKnownCity(raw: string): string | null {
  return KNOWN.get(normalize(raw)) ?? null;
}

/**
 * Проверка через OpenStreetMap для городов, которых нет в списке.
 * Nominatim просит указывать User-Agent и не чаще запроса в секунду — для бота это нормально.
 */
async function lookupOsm(raw: string): Promise<string | null> {
  const query = normalize(raw);
  if (query.length < 2) return null;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 5000);
  try {
    const params = new URLSearchParams({
      q: query,
      format: "jsonv2",
      "accept-language": "ru",
      limit: "5",
      featuretype: "settlement",
    });
    const response = await fetch(`https://nominatim.openstreetmap.org/search?${params}`, {
      headers: { "User-Agent": "bots-admin/1.0 (quizplease)" },
      signal: controller.signal,
    });
    if (!response.ok) return null;

    const rows = (await response.json()) as {
      addresstype?: string;
      type?: string;
      name?: string;
      display_name?: string;
    }[];

    // Сначала сам населённый пункт, и только потом округ или муниципалитет вокруг него.
    const priority = ["city", "town", "village", "hamlet", "municipality"];
    const place = [...rows]
      .filter((row) => priority.includes(row.addresstype ?? row.type ?? ""))
      .sort(
        (a, b) =>
          priority.indexOf(a.addresstype ?? a.type ?? "") -
          priority.indexOf(b.addresstype ?? b.type ?? ""),
      )[0];
    if (!place) return null;

    const name = (place.name || place.display_name?.split(",")[0] || "")
      .replace(/^(городской округ|муниципальный округ|городское поселение|город|г\.)\s+/i, "")
      .trim();
    return name || null;
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

/** Возвращает каноническое название города или null, если это не город. */
export async function validateCity(raw: string): Promise<string | null> {
  const text = raw.trim();
  if (!text || text.length > 60) return null;
  // Числа, e-mail, телефоны — точно не город.
  if (/\d{3,}|@/.test(text)) return null;

  return findKnownCity(text) ?? (await lookupOsm(text));
}
